import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";

const root = new URL("../", import.meta.url).pathname;
const shotsPath = `${root}assets/stock/shots.json`;
const shots = JSON.parse(readFileSync(shotsPath, "utf8"));
const byKey = Object.fromEntries(shots.map((s) => [s.key, s]));

const KEYS = ["mont-1", "mont-2", "mont-6"];
const CUT = 4.2;
const X = 0.9;
const W = 900;
const H = 1100;
const out = "assets/stock/montage.mp4";

const inputs = [];
const parts = [];
KEYS.forEach((k, i) => {
  const s = byKey[k];
  const from = Math.max(0, Math.min(s.best ? s.best[0] : 0, s.dur - CUT - 0.1));
  inputs.push("-ss", String(from), "-t", String(CUT + 0.2), "-i", `${root}assets/stock/${s.file.split("/").pop()}`);
  const scale = Math.max(W / s.w, H / s.h);
  const sw = Math.ceil(s.w * scale);
  const sh = Math.ceil(s.h * scale);
  const x = Math.round(Math.min(Math.max(s.cx * sw - W / 2, 0), sw - W));
  const y = Math.round(Math.min(Math.max(s.cy * sh - H / 2, 0), sh - H));
  parts.push(`[${i}:v]fps=30,scale=${sw}:${sh},crop=${W}:${H}:${x}:${y},trim=duration=${CUT},setpts=PTS-STARTPTS,setsar=1[v${i}]`);
});
let chain = "";
let last = "v0";
for (let i = 1; i < KEYS.length; i++) {
  const o = i === KEYS.length - 1 ? "out" : `x${i}`;
  chain += `;[${last}][v${i}]xfade=transition=fade:duration=${X}:offset=${+(i * (CUT - X)).toFixed(3)}[${o}]`;
  last = o;
}
const filter = `${parts.join(";")}${chain}`;
execFileSync("ffmpeg", ["-hide_banner", "-loglevel", "error", "-y", ...inputs, "-filter_complex", filter, "-map", "[out]", "-c:v", "libx264", "-preset", "slow", "-crf", "16", "-pix_fmt", "yuv420p", "-g", "15", "-movflags", "+faststart", `${root}${out}`], { stdio: "inherit" });

const dur = +execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", `${root}${out}`]).toString().trim();
const rec = { key: "montage", file: out, title: `beat montage (${KEYS.join(", ")})`, w: W, h: H, dur, cx: 0.5, cy: 0.5, best: [0, dur], cut: CUT, notes: "generated by build/montage.mjs, long shots with dissolves" };
const next = shots.filter((s) => s.key !== "montage").concat(rec);
writeFileSync(shotsPath, JSON.stringify(next, null, 2) + "\n");
process.stdout.write(`${out} ${dur}s\n`);
